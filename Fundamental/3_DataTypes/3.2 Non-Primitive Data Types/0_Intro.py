# Non-primitive data types are data types that are not built into the programming language. They are typically created by the programmer and can be used to represent more complex data structures. Examples of non-primitive data types include lists, dictionaries, sets, and tuples in Python.

# A list is an ordered , mutable, duplicate collection of items
my_list = [1, 2, 3, 4, 5]
print(my_list)

# Tuple is an ordered , immutable, duplicate collection of items
gender_tuple = ("Male" ,"Female" , "Other")
print(gender_tuple)

tsubject_tuple = ("Maths", "Science", "English" , "Maths")
print(tsubject_tuple)

# Set is an unordered , mutable, unique collection of items
my_set = {1, 2, 3, 4, 5, 5, 5}
print(my_set)

clu_member_set = {"Alice", "Bob", "Charlie", "David" , "Alice"}
print(clu_member_set)

# A dictionary is an unordered , mutable, unique keys collection of key-value pairs
my_dict = {"Agasthya" : 23,
           "Arav" : 23,
           "Rohan" : 18}
print(my_dict)