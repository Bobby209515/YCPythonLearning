list1 = [45,89,34,23,67,12,90,34,56,78]

print("The list is:", list1)

print("Accessing elements by index numbers:")
print("The first element in the list is:", list1[0])
print("The second element in the list is:", list1[1])
print("The last element in the list is:", list1[9])

# Backward indexing
print("Backward indexing:")
print("The last element in the list is:", list1[-1])
print("The second last element in the list is:", list1[-2]) 
print("The third last element in the list is:", list1[-3]) 